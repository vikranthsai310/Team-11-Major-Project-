"""Build the hosted dashboard for Vercel: static pages plus one serverless function.

    python scripts/export_site.py                  # writes site/
    python scripts/export_site.py --episodes 10
    cd site && vercel deploy --prod

The local dashboard (``scripts/dashboard.py``) computes everything on demand from the
92-day dataset and the trained forecaster. Neither fits in a serverless function, so
the hosted copy is the same frontend over precomputed answers:

* **Results** — ``compare_payload`` written once, exactly what the local view serves.
* **Simulator** — every policy at every traffic level for ``--episodes`` of the 100
  test days, replayed through ``run_episode`` as the local view does.
* **Live** — still live: ``api/live.py`` runs ``batcher.dashboard.live`` against
  preprod through Blockfrost, with ``BLOCKFROST_PROJECT_ID`` set in the Vercel
  project's environment (never in these files). Responses are cached at the edge
  for 30 s so a busy page cannot exhaust the Blockfrost free tier.

The frontend is unchanged: ``vercel.json`` rewrites its ``/api/...`` requests onto
the JSON files. Nothing secret is copied: ``.env`` and signing keys stay out, and
only public on-chain records go in.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

from batcher.dashboard.data import (
    EVALUATION,
    RATES,
    REPLAY_POLICIES,
    EpisodeLibrary,
    compare_payload,
)

REPO = Path(__file__).resolve().parents[1]
STATIC = REPO / "src" / "batcher" / "dashboard" / "static"
MARKER = ".hosted-dashboard"

# What api/live.py imports, and the public on-chain records it reads.
FUNCTION_PACKAGES = ["config", "build", "onchain"]
FUNCTION_FILES = [
    "src/batcher/__init__.py",
    "src/batcher/dashboard/__init__.py",
    "src/batcher/dashboard/live.py",
    "onchain/plutus.json",
    "onchain/deployment.preprod.json",
    "experiments/phase7-preprod-demo/manifest.json",
]
# The function's direct dependencies. requirements.txt pins them, and everything they
# pull in, to the versions installed here: the ones the test suite ran against.
FUNCTION_REQUIREMENTS = ["pycardano", "blockfrost-python"]

LIVE_FUNCTION = '''"""GET /api/live — the deployed DEX on preprod, read now.

Generated by scripts/export_site.py.
"""

import json
import os
import sys
from http.server import BaseHTTPRequestHandler
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
os.environ.setdefault("CARDANO_NETWORK", "preprod")

from batcher.dashboard.live import LiveSource  # noqa: E402

SOURCE = LiveSource(ttl_seconds=30.0)


class handler(BaseHTTPRequestHandler):  # noqa: N801 - the name Vercel looks for
    def do_GET(self):  # noqa: N802
        # The edge cache keys on the query string, so ?x=1, ?x=2, ... would each reach
        # Blockfrost. The page never sends one; refuse it before any chain read.
        if "?" in self.path:
            self.send_response(400)
            self.send_header("Content-Length", "0")
            self.end_headers()
            return
        payload = dict(SOURCE())
        if not payload.get("available"):
            # The detail goes to the function log, not to the public page.
            print(f"live view unavailable: {payload.get('reason')}", flush=True)
            payload["reason"] = "the chain could not be read just now"
        body = json.dumps(payload, allow_nan=False).encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        fresh = payload.get("available")
        cache = "s-maxage=30, stale-while-revalidate=60" if fresh else "s-maxage=10"
        self.send_header("Cache-Control", f"public, max-age=0, {cache}")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
'''

SECURITY_HEADERS = [
    {"key": "X-Content-Type-Options", "value": "nosniff"},
    {"key": "Referrer-Policy", "value": "no-referrer"},
    {"key": "X-Frame-Options", "value": "DENY"},
    {"key": "Permissions-Policy", "value": "camera=(), microphone=(), geolocation=()"},
    {
        # Scripts and styles are all self-hosted; inline style attributes are used for
        # animation delays, so style-src needs 'unsafe-inline' and script-src does not.
        "key": "Content-Security-Policy",
        "value": "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; "
        "img-src 'self' data:; connect-src 'self'; frame-ancestors 'none'; base-uri 'none'; "
        "form-action 'none'",
    },
]


def vercel_config() -> dict:
    return {
        "rewrites": [
            {"source": "/api/catalogue", "destination": "/data/catalogue.json"},
            {"source": "/api/compare", "destination": "/data/compare.json"},
            {
                "source": "/api/replay",
                "has": [
                    {"type": "query", "key": "policy", "value": "(?<policy>[a-z0-9]+)"},
                    {"type": "query", "key": "rate", "value": "(?<rate>[a-z]+)"},
                    {"type": "query", "key": "episode", "value": "(?<episode>[0-9]+)"},
                ],
                "destination": "/data/replay/:policy-:rate-:episode.json",
            },
        ],
        "functions": {
            "api/live.py": {
                "maxDuration": 30,
                "excludeFiles": "{data/**,static/**,index.html}",
            }
        },
        "headers": [{"source": "/(.*)", "headers": SECURITY_HEADERS}],
    }


def pick_episodes(congested: list[float], count: int) -> list[int]:
    """Evenly spaced test days, always including the most congested one."""
    total = len(congested)
    count = max(1, min(count, total))
    chosen = {round(i * (total - 1) / max(1, count - 1)) for i in range(count)}
    busiest = max(range(total), key=congested.__getitem__)
    if busiest not in chosen:
        chosen.discard(min(chosen, key=lambda i: abs(i - busiest)))  # its nearest neighbour
        chosen.add(busiest)
    return sorted(chosen)


def write_json(path: Path, payload) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, allow_nan=False, separators=(",", ":")), encoding="utf-8")


# Never uploaded: `vercel link` writes a project token to .env.local.
VERCEL_IGNORE = [".env*", ".vercel", MARKER]


def prepare(out: Path) -> None:
    """Empty ``out`` for a fresh build, keeping the Vercel link (``.vercel``, ``.env.local``)."""
    if out.exists():
        if not (out / MARKER).exists():
            raise SystemExit(f"{out} exists and was not made by this script; refusing to delete it")
        for item in out.iterdir():
            if item.name == ".vercel" or item.name.startswith(".env"):
                continue
            shutil.rmtree(item) if item.is_dir() else item.unlink()
    out.mkdir(parents=True, exist_ok=True)
    (out / MARKER).write_text("generated by scripts/export_site.py\n", encoding="utf-8")
    (out / ".vercelignore").write_text("\n".join(VERCEL_IGNORE) + "\n", encoding="utf-8")


def copy_frontend(out: Path) -> None:
    shutil.copy2(STATIC / "index.html", out / "index.html")
    (out / "static").mkdir()
    for item in STATIC.iterdir():
        if item.is_file():
            shutil.copy2(item, out / "static" / item.name)


def copy_function(out: Path) -> None:
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
    for package in FUNCTION_PACKAGES:
        shutil.copytree(
            REPO / "src" / "batcher" / package, out / "src" / "batcher" / package, ignore=ignore
        )
    for name in FUNCTION_FILES:
        (out / name).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(REPO / name, out / name)
    (out / "api").mkdir()
    (out / "api" / "live.py").write_text(LIVE_FUNCTION, encoding="utf-8")
    (out / "requirements.txt").write_text("\n".join(pinned_requirements()) + "\n", encoding="utf-8")


def pinned_requirements(roots: list[str] = FUNCTION_REQUIREMENTS) -> list[str]:
    """``name==version`` for the roots and their Linux dependency closure, as installed."""
    from importlib.metadata import PackageNotFoundError, distribution

    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name

    linux = {"extra": "", "sys_platform": "linux", "platform_system": "Linux", "os_name": "posix"}
    pins, todo = {}, list(roots)
    while todo:
        name = canonicalize_name(todo.pop())
        if name in pins or name in {"setuptools", "pip"}:
            continue
        try:
            dist = distribution(name)
        except PackageNotFoundError:
            raise SystemExit(f"{name} is not installed; run: pip install -e .[dev]") from None
        pins[name] = dist.version
        for line in dist.requires or []:
            requirement = Requirement(line)
            if requirement.marker is None or requirement.marker.evaluate(linux):
                todo.append(requirement.name)
    return [f"{name}=={version}" for name, version in sorted(pins.items())]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=REPO / "site")
    parser.add_argument("--episodes", type=int, default=10)
    parser.add_argument("--data", type=Path, default=None)
    parser.add_argument(
        "--models", type=Path, default=REPO / "experiments/phase3-forecaster/models"
    )
    args = parser.parse_args(argv)

    data = args.data or next(
        iter(sorted((REPO / "data/processed").glob("d1_blocks_*.parquet"), reverse=True)), None
    )
    library = EpisodeLibrary(data, args.models)
    print("loading the test episodes…", flush=True)
    library.load()
    if library.state != "ready":
        print(f"cannot build the Simulator view: {library.message}", file=sys.stderr)
        return 1
    if library.forecaster != "LightGBM":
        print(
            f"the forecaster is {library.forecaster!r}, not LightGBM — rebuild it with "
            "scripts/train_forecaster.py first",
            file=sys.stderr,
        )
        return 1

    prepare(args.out)
    copy_frontend(args.out)
    copy_function(args.out)
    write_json(args.out / "data" / "compare.json", compare_payload(EVALUATION))

    chosen = pick_episodes(library.congested, args.episodes)
    catalogue = library.catalogue()
    catalogue["episodes"] = [e for e in catalogue["episodes"] if e["index"] in chosen]
    catalogue["message"] = (
        f"This online copy carries {len(chosen)} of the {len(library.episodes)} test days. "
        "Pick a policy and a test day, then Load."
    )
    write_json(args.out / "data" / "catalogue.json", catalogue)

    jobs = [(p, r, i) for i in chosen for r in RATES for p in REPLAY_POLICIES]
    for done, (policy, rate, index) in enumerate(jobs, 1):
        write_json(
            args.out / "data" / "replay" / f"{policy}-{rate}-{index}.json",
            library.replay(policy, rate, index),
        )
        if done % 15 == 0 or done == len(jobs):
            print(f"  replays {done}/{len(jobs)}", flush=True)

    write_json(args.out / "vercel.json", vercel_config())
    size = sum(f.stat().st_size for f in args.out.rglob("*") if f.is_file())
    print(
        f"site written to {args.out} ({size / 1e6:.1f} MB). "
        f"Deploy: cd {args.out.name} && vercel deploy --prod"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
